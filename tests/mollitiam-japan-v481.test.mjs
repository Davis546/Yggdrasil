import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const game=readFileSync(new URL('public/game.js',root),'utf8');
const html=readFileSync(new URL('public/index.html',root),'utf8');
const alt=readFileSync(new URL('public/game.html',root),'utf8');
const healExpr=game.match(/const healRate=([^;]+);const heal=Math.round\(ally.maxHp\*healRate\)/)?.[1];
assert.ok(healExpr,'Mollitiam E heal formula exists');
const rate=new Function('player','isNordic',`return ${healExpr};`);
assert.equal(rate({mollitiamHeartTime:0},()=>true),.25);
assert.equal(rate({mollitiamHeartTime:1},()=>true),.35);
assert.equal(rate({mollitiamHeartTime:0},()=>false),.125);
assert.equal(rate({mollitiamHeartTime:1},()=>false),.175);
const hurt=game.slice(game.indexOf('function hurtPlayer(d,'),game.indexOf('function update',game.indexOf('function hurtPlayer(d,')));
const inv= hurt.match(/YG_AUDIO.play\('hurt'\);player.invuln=([^;]+);/)?.[1];
assert.ok(inv,'per-hit invulnerability formula exists');
const invCalc=new Function('player','isNordic',`return ${inv};`);
assert.equal(invCalc({type:'mollitiam'},()=>false),.18);
assert.equal(invCalc({type:'mollitiam'},()=>true),.76);
assert.equal(invCalc({type:'kris'},()=>false),.76);
for(const h of [html,alt])assert.match(h,/game\.js\?v=493/);
console.log('OK Mollitiam JP: E cura metade; .18s invulnerabilidade; Nórdico preservado; demais heróis preservados');
